#!/usr/bin/env python3
"""Turns tokens.json into code for every client and rejects colors that are hard to read."""

import json
import re
from pathlib import Path

HERE = Path(__file__).parent
ROOT = HERE.parent
HEADER = "Generated by design/generate.py from design/tokens.json. Do not edit."
MIN_CONTRAST = 4.5


def luminance(color):
    channels = [int(color[i : i + 2], 16) / 255 for i in (1, 3, 5)]
    linear = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


def contrast(first, second):
    high, low = sorted((luminance(first), luminance(second)), reverse=True)
    return (high + 0.05) / (low + 0.05)


def check(tokens):
    failures = []
    for mode, colors in tokens["color"].items():
        for text, ground in tokens["contrast"]:
            ratio = contrast(colors[text], colors[ground])
            if ratio < MIN_CONTRAST:
                failures.append(f"{mode}: {text} on {ground} is {ratio:.2f}")
    if failures:
        raise SystemExit("\n".join(failures))


def snake(name):
    return re.sub(r"([A-Z])", r"_\1", name).upper()


def rust(tokens):
    lines = [f"// {HEADER}", "", "pub struct Palette {"]
    names = list(tokens["color"]["light"])
    lines += [f"    pub {snake(name).lower()}: u32," for name in names]
    lines += ["}", ""]
    for mode, colors in tokens["color"].items():
        lines.append(f"pub const {mode.upper()}: Palette = Palette {{")
        lines += [f"    {snake(n).lower()}: 0x{colors[n][1:].lower()}," for n in names]
        lines += ["};", ""]
    for group in ("space", "radius", "type"):
        for name, value in tokens[group].items():
            lines.append(f"pub const {group.upper()}_{name.upper()}: f32 = {value}.0;")
    return "\n".join(lines) + "\n"


def kotlin(tokens):
    lines = [f"// {HEADER}", "package app.solferry.design", "", "import androidx.compose.ui.graphics.Color", ""]
    for mode, colors in tokens["color"].items():
        lines.append(f"object {mode.capitalize()}Colors {{")
        lines += [f"    val {n} = Color(0xFF{v[1:]})" for n, v in colors.items()]
        lines += ["}", ""]
    for group in ("space", "radius", "type", "motion"):
        lines.append(f"object {group.capitalize()}Tokens {{")
        lines += [f"    const val {n} = {v}" for n, v in tokens[group].items()]
        lines += ["}", ""]
    return "\n".join(lines).rstrip() + "\n"


def swift(tokens):
    lines = [f"// {HEADER}", "import SwiftUI", "", "extension Color {", "    init(hex: UInt32) {"]
    lines += [
        "        self.init(red: Double(hex >> 16 & 255) / 255, green: Double(hex >> 8 & 255) / 255, blue: Double(hex & 255) / 255)",
        "    }",
        "}",
        "",
    ]
    for mode, colors in tokens["color"].items():
        lines.append(f"enum {mode.capitalize()}Colors {{")
        lines += [f"    static let {n} = Color(hex: 0x{v[1:]})" for n, v in colors.items()]
        lines += ["}", ""]
    for group in ("space", "radius", "type", "motion"):
        lines.append(f"enum {group.capitalize()}Tokens {{")
        lines += [f"    static let {n}: Double = {v}" for n, v in tokens[group].items()]
        lines += ["}", ""]
    return "\n".join(lines).rstrip() + "\n"


def main():
    tokens = json.loads((HERE / "tokens.json").read_text())
    check(tokens)
    (ROOT / "crates/solferry-desktop/src/tokens.rs").write_text(rust(tokens))
    (HERE / "generated/SolferryTokens.kt").write_text(kotlin(tokens))
    (HERE / "generated/SolferryTokens.swift").write_text(swift(tokens))


if __name__ == "__main__":
    main()
