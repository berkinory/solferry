#!/usr/bin/env python3
"""Turns tokens.json into code for every client and rejects colors that are hard to read."""

import json
import re
import subprocess
from pathlib import Path

HERE = Path(__file__).parent
ROOT = HERE.parent
HEADER = "Generated by design/generate.py from design/tokens.json. Do not edit."
MIN_CONTRAST = 4.5


def luminance(color):
    channels = [int(color[i : i + 2], 16) / 255 for i in (1, 3, 5)]
    linear = [c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
    return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]


def contrast(first, second):
    high, low = sorted((luminance(first), luminance(second)), reverse=True)
    return (high + 0.05) / (low + 0.05)


def mix(color, toward, amount):
    first = [int(color[i : i + 2], 16) for i in (1, 3, 5)]
    second = [int(toward[i : i + 2], 16) for i in (1, 3, 5)]
    channels = [round(a * amount + b * (1 - amount)) for a, b in zip(first, second)]
    return "#" + "".join(f"{channel:02X}" for channel in channels)


def derive(tokens):
    """Adds the primary button's fill, hover and border, mixed from ultramarine toward the deep end."""
    for mode, colors in tokens["color"].items():
        for name, amount in tokens["button"][mode].items():
            key = "primary" + name.capitalize()
            colors[key] = mix(tokens["button"]["base"], colors["primaryDeep"], amount)
    return tokens


def check(tokens):
    failures = []
    for mode, colors in tokens["color"].items():
        for text, ground in tokens["contrast"]:
            ratio = contrast(colors[text], colors[ground])
            if ratio < MIN_CONTRAST:
                failures.append(f"{mode}: {text} on {ground} is {ratio:.2f}")
    if failures:
        raise SystemExit("\n".join(failures))


def snake(name):
    return re.sub(r"([A-Z])", r"_\1", name).upper()


def radii(tokens):
    corner = tokens["corner"]
    well = corner["control"] + corner["gutter"]
    return {
        "floor": corner["floor"],
        "control": corner["control"],
        "field": corner["control"] + corner["frame"],
        "well": well,
        "card": well + corner["frame"],
    }


# A desktop window sits among denser native apps than a phone screen does.
DESKTOP_SCALE = 0.9


def scales(tokens):
    return {"space": tokens["space"], "radius": radii(tokens), "type": tokens["type"]}


def rust(tokens):
    lines = [f"// {HEADER}", "", "pub struct Palette {"]
    names = list(tokens["color"]["light"])
    lines += [f"    pub {snake(name).lower()}: u32," for name in names]
    lines += ["}", ""]
    for mode, colors in tokens["color"].items():
        lines.append(f"pub const {mode.upper()}: Palette = Palette {{")
        lines += [f"    {snake(n).lower()}: 0x{colors[n][1:3].lower()}_{colors[n][3:].lower()}," for n in names]
        lines += ["};", ""]
    for mode, colors in tokens["identity"].items():
        lines.append(f"pub const IDENTITY_{mode.upper()}: [u32; {len(colors)}] = [")
        lines += [f"    0x{color[1:3].lower()}_{color[3:].lower()}," for color in colors]
        lines.append("];")
    lines.append("")
    for name, value in tokens["font"].items():
        lines.append(f'pub const FONT_{name.upper()}: &str = "{value}";')
    lines.append("")
    for group, values in scales(tokens).items():
        for name, value in values.items():
            lines.append(f"pub const {group.upper()}_{name.upper()}: f32 = {value}.0;")
    return "\n".join(lines) + "\n"


def kotlin(tokens):
    lines = [f"// {HEADER}", "package app.solferry.design", "", "import androidx.compose.ui.graphics.Color", ""]
    for mode, colors in tokens["color"].items():
        lines.append(f"object {mode.capitalize()}Colors {{")
        lines += [f"    val {n} = Color(0xFF{v[1:]})" for n, v in colors.items()]
        lines += ["}", ""]
    lines.append("object IdentityColors {")
    for mode, colors in tokens["identity"].items():
        values = ", ".join(f"Color(0xFF{color[1:]})" for color in colors)
        lines.append(f"    val {mode} = listOf({values})")
    lines += ["}", ""]
    for group, values in {**scales(tokens), "motion": tokens["motion"]}.items():
        lines.append(f"object {group.capitalize()}Tokens {{")
        lines += [f"    const val {n} = {v}" for n, v in values.items()]
        lines += ["}", ""]
    return "\n".join(lines).rstrip() + "\n"


def swift(tokens):
    lines = [f"// {HEADER}", "import SwiftUI", "", "extension Color {", "    init(hex: UInt32) {"]
    lines += [
        "        self.init(red: Double(hex >> 16 & 255) / 255, green: Double(hex >> 8 & 255) / 255, blue: Double(hex & 255) / 255)",
        "    }",
        "}",
        "",
    ]
    for mode, colors in tokens["color"].items():
        lines.append(f"enum {mode.capitalize()}Colors {{")
        lines += [f"    static let {n} = Color(hex: 0x{v[1:]})" for n, v in colors.items()]
        lines += ["}", ""]
    lines.append("enum IdentityColors {")
    for mode, colors in tokens["identity"].items():
        values = ", ".join(f"Color(hex: 0x{color[1:]})" for color in colors)
        lines.append(f"    static let {mode} = [{values}]")
    lines += ["}", ""]
    for group, values in {**scales(tokens), "motion": tokens["motion"]}.items():
        lines.append(f"enum {group.capitalize()}Tokens {{")
        lines += [f"    static let {n}: Double = {v}" for n, v in values.items()]
        lines += ["}", ""]
    return "\n".join(lines).rstrip() + "\n"


def desktop_colors(c):
    return {
        "background": c["page"],
        "foreground": c["ink"],
        "border": c["line"],
        "input.border": c["line"],
        "ring": c["primary"],
        "caret": c["ink"],
        "link": c["link"],
        "link.hover": c["link"],
        "link.active": c["link"],
        "muted.background": c["raised"],
        "muted.foreground": c["inkMuted"],
        "accent.background": c["raised"],
        "accent.foreground": c["ink"],
        "secondary.background": c["control"],
        "secondary.foreground": c["ink"],
        "secondary.hover.background": c["raised"],
        "secondary.active.background": c["line"],
        "primary.background": c["primary"],
        "primary.foreground": c["onPrimary"],
        "primary.hover.background": c["primaryHover"],
        "primary.active.background": c["primaryFill"],
        "danger.background": c["dangerFill"],
        "danger.foreground": c["onPrimary"],
        "success.background": c["success"],
        "warning.background": c["warning"],
        "popover.background": c["page"],
        "popover.foreground": c["ink"],
        "switch.background": c["line"],
        "switch.thumb.background": c["page"],
        "scrollbar.background": "#00000000",
        "scrollbar.thumb.background": c["line"],
        "scrollbar.thumb.hover.background": c["inkMuted"],
        "selection.background": c["primary"] + "55",
        "title_bar.background": c["page"],
        "title_bar.border": c["page"],
        "window.border": c["line"],
    }


def desktop_theme(tokens):
    themes = []
    for mode, colors in tokens["color"].items():
        themes.append(
            {
                "name": f"Solferry {mode.capitalize()}",
                "mode": mode,
                "font.family": tokens["font"]["sans"],
                "font.size": tokens["type"]["body"],
                "mono_font.family": tokens["font"]["mono"],
                "mono_font.size": tokens["type"]["caption"],
                "radius": tokens["corner"]["control"],
                "radius.lg": radii(tokens)["field"],
                "shadow": False,
                "colors": desktop_colors(colors),
            }
        )
    return json.dumps({"name": "Solferry", "author": "Solferry", "themes": themes}, indent=2) + "\n"


def main():
    tokens = derive(json.loads((HERE / "tokens.json").read_text()))
    check(tokens)
    desktop = {**tokens, **{group: {name: round(size * DESKTOP_SCALE) for name, size in tokens[group].items()} for group in ("type", "space", "corner")}}
    rust_tokens = ROOT / "crates/solferry-desktop/src/tokens.rs"
    rust_tokens.write_text(rust(desktop))
    subprocess.run(["rustfmt", "--edition", "2024", str(rust_tokens)], check=True, cwd=ROOT)
    (ROOT / "crates/solferry-desktop/src/theme.json").write_text(desktop_theme(desktop))
    (HERE / "generated/SolferryTokens.kt").write_text(kotlin(tokens))
    (HERE / "generated/SolferryTokens.swift").write_text(swift(tokens))


if __name__ == "__main__":
    main()
